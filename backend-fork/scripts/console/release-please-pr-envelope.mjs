/**
 * Canonical Release Please pull-request metadata derived only from the exact
 * parent/candidate release blobs and the authenticated bot commit subject.
 *
 * This module is deliberately pure: it has no filesystem, process, network, or
 * credential capability. Both the native action binding and the permission
 * fallback use it so a fallback cannot invent a title or release-note body.
 */
import { validateReleaseMetadataBytes } from '../check-release-metadata.mjs';
import {
  RELEASE_PLEASE_HEAD_REF,
  RELEASE_PLEASE_PATHS,
  RELEASE_PLEASE_SUBJECT,
} from './release-please-bot-candidate.mjs';

export const RELEASE_PLEASE_ACTION_BODY_PREFIX = ':robot: I have created a release *beep* *boop*\n---\n\n\n';
export const RELEASE_PLEASE_ACTION_BODY_SUFFIX = '\n\n---\nThis PR was generated with [Release Please](https://github.com/googleapis/release-please). See [documentation](https://github.com/googleapis/release-please#release-please).';
export const RELEASE_PLEASE_PENDING_LABEL = 'autorelease: pending';

const CHANGELOG_PREFIX = '# Changelog\n\n';
const MAX_PR_TITLE_BYTES = 256;
const MAX_PR_BODY_BYTES = 64 * 1024;

function fail(message) {
  throw new Error(`release-please PR envelope: ${message}`);
}

function exactUtf8(value, label, maximumBytes = 8 * 1024 * 1024) {
  if (!Buffer.isBuffer(value) || value.length === 0 || value.length > maximumBytes) {
    fail(`${label} must be non-empty exact bytes no larger than ${maximumBytes}`);
  }
  const text = value.toString('utf8');
  if (!Buffer.from(text, 'utf8').equals(value)) fail(`${label} must be valid UTF-8`);
  if (text.includes('\r')) fail(`${label} must use canonical LF line endings`);
  if (text.includes('\0')) fail(`${label} must not contain NUL bytes`);
  return text;
}

function exactSubject(subject, version) {
  if (typeof subject !== 'string' || !RELEASE_PLEASE_SUBJECT.test(subject)) {
    fail('commit subject must match the protected release subject');
  }
  if (Buffer.byteLength(subject, 'utf8') > MAX_PR_TITLE_BYTES || subject.includes('\r') || subject.includes('\n')) {
    fail('commit subject exceeds the canonical PR-title envelope');
  }
  const match = subject.match(/ release (\d+\.\d+\.\d+)$/);
  if (!match || match[1] !== version) {
    fail(`commit subject must name manifest version ${version}`);
  }
  return subject;
}

function releaseNotesFromChangelogs(baseChangelog, headChangelog) {
  const base = exactUtf8(baseChangelog, 'base CHANGELOG.md');
  const head = exactUtf8(headChangelog, 'head CHANGELOG.md');
  if (!base.startsWith(CHANGELOG_PREFIX) || !head.startsWith(CHANGELOG_PREFIX)) {
    fail('both changelogs must begin with the canonical heading');
  }
  const priorReleases = base.slice(CHANGELOG_PREFIX.length);
  if (priorReleases.length === 0) fail('base CHANGELOG.md must contain prior release bytes');
  const suffix = `\n\n${priorReleases}`;
  if (!head.endsWith(suffix)) {
    fail('head CHANGELOG.md must exactly prepend one release block to the base changelog');
  }
  const notes = head.slice(CHANGELOG_PREFIX.length, -suffix.length);
  if (notes.length === 0 || notes.startsWith('\n') || notes.endsWith('\n')) {
    fail('prepended release notes must be one non-empty canonical block');
  }
  const reconstructed = `${CHANGELOG_PREFIX}${notes}${suffix}`;
  if (reconstructed !== head) fail('release-note insertion is ambiguous');
  return notes;
}

export function deriveReleasePleasePrEnvelope({
  baseManifest,
  headManifest,
  baseChangelog,
  headChangelog,
  subject,
  headRef,
} = {}) {
  if (typeof headRef !== 'string' || !RELEASE_PLEASE_HEAD_REF.test(headRef)) {
    fail('head ref is outside the exact release-please class');
  }
  const metadata = validateReleaseMetadataBytes({ baseManifest, headManifest, headChangelog });
  const title = exactSubject(subject, metadata.headVersion);
  const releaseNotes = releaseNotesFromChangelogs(baseChangelog, headChangelog);
  const body = `${RELEASE_PLEASE_ACTION_BODY_PREFIX}${releaseNotes}${RELEASE_PLEASE_ACTION_BODY_SUFFIX}`;
  if (Buffer.byteLength(body, 'utf8') > MAX_PR_BODY_BYTES) {
    fail(`canonical PR body exceeds ${MAX_PR_BODY_BYTES} bytes`);
  }
  return Object.freeze({
    headBranchName: headRef,
    baseBranchName: 'dev',
    title,
    body,
    labels: Object.freeze([RELEASE_PLEASE_PENDING_LABEL]),
    files: Object.freeze([]),
    releasePaths: Object.freeze([...RELEASE_PLEASE_PATHS]),
    version: metadata.headVersion,
  });
}

export function assertReleasePleasePrEnvelope(actionPr, expected) {
  if (!actionPr || typeof actionPr !== 'object' || !expected || typeof expected !== 'object') {
    fail('action and expected PR envelopes must be objects');
  }
  for (const key of ['headBranchName', 'baseBranchName', 'title', 'body']) {
    if (actionPr[key] !== expected[key]) fail(`PR ${key} does not match exact generated bytes`);
  }
  if (JSON.stringify(actionPr.labels) !== JSON.stringify(expected.labels)) {
    fail('PR labels must equal the canonical pending-label set');
  }
  if (!Array.isArray(actionPr.files)) fail('PR files output must be an array');
  return expected;
}
