#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const args = new Map();
for (let index = 2; index < process.argv.length; index += 1) {
  const arg = process.argv[index];
  if (arg === "--check" || arg === "--write") args.set(arg, true);
  else if (arg === "--registry" || arg === "--output") args.set(arg, process.argv[++index]);
  else throw new Error(`unknown argument: ${arg}`);
}
if (args.has("--check") === args.has("--write")) {
  throw new Error("usage: generate-trivy-dev-codegen-exceptions.mjs <--check|--write> [--registry path] [--output path]");
}
const registryPath = resolve(root, args.get("--registry") ?? "security/node-audit-exceptions.json");
const outputPath = resolve(root, args.get("--output") ?? "security/trivy-dev-codegen-exceptions.yaml");

function yamlString(value) {
  return JSON.stringify(value);
}

export function validateRegistry(registry, now = new Date()) {
  if (registry.schema_version !== "node-audit-exceptions-v1" || !Array.isArray(registry.entries)) {
    throw new Error("node audit exception registry must be node-audit-exceptions-v1 with an entries array");
  }
  const today = now.toISOString().slice(0, 10);
  for (const [index, entry] of registry.entries.entries()) {
    const label = `exception[${index}]`;
    for (const key of ["advisory", "package", "version", "path", "scope", "owner", "tracking", "rationale", "trivy_statement", "expires_on"]) {
      if (typeof entry[key] !== "string" || !entry[key].trim()) throw new Error(`${label} missing ${key}`);
    }
    if (entry.scope !== "dev-codegen") throw new Error(`${label} must be dev-codegen scoped`);
    if (!/^GHSA-[a-z0-9]{4}-[a-z0-9]{4}-[a-z0-9]{4}$/i.test(entry.advisory)) throw new Error(`${label} has invalid advisory`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(entry.expires_on) || entry.expires_on <= today) throw new Error(`${label} is expired`);
    const expiresAt = Date.parse(`${entry.expires_on}T00:00:00Z`);
    if (!Number.isFinite(expiresAt) || expiresAt - now.getTime() > 30 * 24 * 60 * 60 * 1000) throw new Error(`${label} exceeds 30-day TTL`);
    if (!entry.path.startsWith("node_modules/") || entry.path.includes("\n")) throw new Error(`${label} has invalid package path`);
  }
}

export function buildTrivyIgnorefile(registry, now = new Date()) {
  validateRegistry(registry, now);
  const lines = [
    "# Generated by scripts/generate-trivy-dev-codegen-exceptions.mjs; do not edit.",
    "# Canonical source: security/node-audit-exceptions.json.",
    registry.entries.length ? "vulnerabilities:" : "vulnerabilities: []",
  ];
  for (const entry of registry.entries) {
    const purl = `pkg:npm/${encodeURIComponent(entry.package)}@${entry.version}`;
    lines.push(
      `  - id: ${entry.advisory}`,
      "    purls:",
      `      - ${purl}`,
      "    paths:",
      `      - ${entry.path}`,
      `    expired_at: ${entry.expires_on}`,
      `    statement: ${yamlString(entry.trivy_statement)}`,
    );
  }
  return `${lines.join("\n")}\n`;
}

const registry = JSON.parse(readFileSync(registryPath, "utf8"));
const expected = buildTrivyIgnorefile(registry);
if (args.has("--write")) {
  writeFileSync(outputPath, expected);
  console.log(`TRIVY_DEV_CODEGEN_EXCEPTIONS_WRITTEN ${outputPath}`);
} else {
  const actual = readFileSync(outputPath, "utf8");
  if (actual !== expected) throw new Error("Trivy dev/codegen exception YAML differs from the canonical JSON projection; regenerate with --write");
  console.log("TRIVY_DEV_CODEGEN_EXCEPTIONS_PARITY_PASS");
}
