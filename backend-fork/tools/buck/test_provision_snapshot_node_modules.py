#!/usr/bin/env python3
"""Regression locks for hermetic snapshot Node dependency provisioning."""

import importlib.util
import json
import shutil
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).parent
SPEC = importlib.util.spec_from_file_location("provision_snapshot_node_modules", ROOT / "provision_snapshot_node_modules.py")
assert SPEC and SPEC.loader
PROVISION = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(PROVISION)


class SnapshotNodeModulesTests(unittest.TestCase):
    def make_tree(self) -> tuple[Path, Path, Path]:
        temp = Path(tempfile.mkdtemp(prefix="snapshot-node-deps-"))
        caller, snapshot = temp / "caller", temp / "snapshot"
        lock = {
            "lockfileVersion": 3,
            "packages": {
                "": {"devDependencies": {"openapi-typescript": "7.13.0"}},
                "node_modules/openapi-typescript": {"version": "7.13.0"},
            },
        }
        for root in (caller, snapshot):
            root.mkdir()
            (root / "package.json").write_text('{"devDependencies":{"openapi-typescript":"7.13.0"}}\n')
            (root / "package-lock.json").write_text(json.dumps(lock))
        manifest = caller / "node_modules/openapi-typescript/package.json"
        manifest.parent.mkdir(parents=True)
        manifest.write_text('{"name":"openapi-typescript","version":"7.13.0"}\n')
        return temp, caller, snapshot

    def test_links_verified_dependencies_without_copying_or_ancestor_resolution(self) -> None:
        temp, caller, snapshot = self.make_tree()
        try:
            destination = PROVISION.provision(caller, snapshot)
            self.assertTrue(destination.is_symlink())
            self.assertEqual((caller / "node_modules").resolve(), destination.resolve())
            self.assertTrue((snapshot / "node_modules/openapi-typescript/package.json").is_file())
        finally:
            shutil.rmtree(temp)

    def test_missing_or_lock_inconsistent_dependencies_fail_closed(self) -> None:
        temp, caller, snapshot = self.make_tree()
        try:
            shutil.rmtree(caller / "node_modules")
            with self.assertRaisesRegex(PROVISION.ProvisionError, "node_modules is absent"):
                PROVISION.provision(caller, snapshot)
        finally:
            shutil.rmtree(temp)
        temp, caller, snapshot = self.make_tree()
        try:
            (caller / "node_modules/openapi-typescript/package.json").write_text('{"version":"0.0.0"}\n')
            with self.assertRaisesRegex(PROVISION.ProvisionError, "differs from lockfile"):
                PROVISION.provision(caller, snapshot)
        finally:
            shutil.rmtree(temp)

    def add_locked_package(self, caller: Path, snapshot: Path, name: str, entry: dict, installed_version: str | None) -> None:
        for root in (caller, snapshot):
            lock = json.loads((root / "package-lock.json").read_text())
            lock["packages"]["node_modules/" + name] = entry
            (root / "package-lock.json").write_text(json.dumps(lock))
        if installed_version is not None:
            manifest = caller / "node_modules" / name / "package.json"
            manifest.parent.mkdir(parents=True, exist_ok=True)
            manifest.write_text(json.dumps({"name": name, "version": installed_version}))

    def test_absent_optional_or_platform_incompatible_packages_are_permitted(self) -> None:
        temp, caller, snapshot = self.make_tree()
        try:
            self.add_locked_package(caller, snapshot, "optional", {"version": "1.0.0", "optional": True}, None)
            self.add_locked_package(caller, snapshot, "linux-only", {"version": "1.0.0", "os": ["linux"]}, None)
            PROVISION.provision(caller, snapshot, platform="darwin", arch="arm64")
        finally:
            shutil.rmtree(temp)

    def test_required_absence_and_installed_optional_mismatch_fail_closed(self) -> None:
        temp, caller, snapshot = self.make_tree()
        try:
            self.add_locked_package(caller, snapshot, "required", {"version": "1.0.0"}, None)
            with self.assertRaisesRegex(PROVISION.ProvisionError, "installed package is absent"):
                PROVISION.provision(caller, snapshot)
        finally:
            shutil.rmtree(temp)
        temp, caller, snapshot = self.make_tree()
        try:
            self.add_locked_package(caller, snapshot, "optional", {"version": "1.0.0", "optional": True}, "0.0.0")
            with self.assertRaisesRegex(PROVISION.ProvisionError, "differs from lockfile"):
                PROVISION.provision(caller, snapshot)
        finally:
            shutil.rmtree(temp)

    def test_candidate_digest_mismatch_fails_before_linking(self) -> None:
        temp, caller, snapshot = self.make_tree()
        try:
            (snapshot / "package-lock.json").write_text('{}\n')
            with self.assertRaisesRegex(PROVISION.ProvisionError, "digest differs"):
                PROVISION.provision(caller, snapshot)
            self.assertFalse((snapshot / "node_modules").exists())
        finally:
            shutil.rmtree(temp)

    def test_link_target_metadata_without_a_version_is_not_a_package(self) -> None:
        temp, caller, snapshot = self.make_tree()
        try:
            target = "tools/npm/minimatch-callable-compat"
            link = "node_modules/@redocly/openapi-core/node_modules/minimatch"
            metadata = "node_modules/@redocly/openapi-core/" + target
            for root in (caller, snapshot):
                lock = json.loads((root / "package-lock.json").read_text())
                lock["packages"].update(
                    {
                        target: {"name": "minimatch", "version": "5.1.9-maintenance.1"},
                        link: {"resolved": target, "link": True},
                        metadata: {"extraneous": True},
                    }
                )
                (root / "package-lock.json").write_text(json.dumps(lock))
            target_manifest = caller / target / "package.json"
            target_manifest.parent.mkdir(parents=True)
            target_manifest.write_text('{"name":"minimatch","version":"5.1.9-maintenance.1"}\n')
            installed_link = caller / link
            installed_link.parent.mkdir(parents=True)
            installed_link.symlink_to(caller / target, target_is_directory=True)

            PROVISION.provision(caller, snapshot)
        finally:
            shutil.rmtree(temp)

    def test_only_validated_link_target_metadata_is_exempt_from_version_requirement(self) -> None:
        packages = {
            "tools/npm/local-target": {"version": "1.0.0"},
            "node_modules/parent/node_modules/local-target": {
                "link": True,
                "resolved": "tools/npm/local-target",
            },
            "node_modules/parent/tools/npm/local-target": {"extraneous": True},
        }
        self.assertNotIn(
            "node_modules/parent/tools/npm/local-target",
            PROVISION.locked_packages({"packages": packages}),
        )

        packages["node_modules/unrelated"] = {"extraneous": True}
        with self.assertRaisesRegex(PROVISION.ProvisionError, "lacks a resolved package version"):
            PROVISION.locked_packages({"packages": packages})

        malformed = dict(packages)
        malformed["node_modules/parent/node_modules/local-target"] = {
            "link": True,
            "resolved": "../outside",
        }
        with self.assertRaisesRegex(PROVISION.ProvisionError, "invalid package-lock path"):
            PROVISION.locked_packages({"packages": malformed})

        missing_target = dict(packages)
        missing_target["node_modules/parent/node_modules/local-target"] = {
            "link": True,
            "resolved": "tools/npm/missing",
        }
        with self.assertRaisesRegex(PROVISION.ProvisionError, "target has no resolved package version"):
            PROVISION.locked_packages({"packages": missing_target})

    def test_link_target_cannot_escape_through_an_intermediate_symlink(self) -> None:
        temp, caller, snapshot = self.make_tree()
        try:
            target = "tools/npm/local-target"
            link = "node_modules/parent/node_modules/local-target"
            metadata = "node_modules/parent/" + target
            outside = temp / "outside/npm/local-target"
            outside.mkdir(parents=True)
            (outside / "package.json").write_text('{"name":"local-target","version":"1.0.0"}\n')
            (caller / "tools").symlink_to(temp / "outside", target_is_directory=True)
            for root in (caller, snapshot):
                lock = json.loads((root / "package-lock.json").read_text())
                lock["packages"].update(
                    {
                        target: {"name": "local-target", "version": "1.0.0"},
                        link: {"resolved": target, "link": True},
                        metadata: {"extraneous": True},
                    }
                )
                (root / "package-lock.json").write_text(json.dumps(lock))
            installed_link = caller / link
            installed_link.parent.mkdir(parents=True)
            installed_link.symlink_to(caller / target, target_is_directory=True)

            with self.assertRaisesRegex(PROVISION.ProvisionError, "target escapes caller"):
                PROVISION.provision(caller, snapshot)
        finally:
            shutil.rmtree(temp)

    def test_lock_paths_reject_non_posix_and_malformed_forms(self) -> None:
        valid_target = "tools/npm/local-target"
        link_path = "node_modules/parent/node_modules/local-target"
        malformed_paths = (
            r"tools\\npm\\local-target",
            "C:/tools/npm/local-target",
            r"C:\\tools\\npm\\local-target",
            "//server/share/local-target",
            "/tools/npm/local-target",
            "tools//npm/local-target",
            "./tools/npm/local-target",
            "tools/../local-target",
        )
        for path in malformed_paths:
            with self.subTest(path=path):
                packages = {
                    valid_target: {"version": "1.0.0"},
                    link_path: {"link": True, "resolved": path},
                }
                with self.assertRaisesRegex(PROVISION.ProvisionError, "invalid package-lock path"):
                    PROVISION.locked_packages({"packages": packages})

                packages = {path: {"version": "1.0.0"}}
                with self.assertRaisesRegex(PROVISION.ProvisionError, "invalid package-lock path"):
                    PROVISION.locked_packages({"packages": packages})

    def test_bare_node_modules_is_not_a_link_target(self) -> None:
        packages = {
            "node_modules": {"version": "1.0.0"},
            "node_modules/parent/node_modules/local-target": {
                "link": True,
                "resolved": "node_modules",
            },
        }
        with self.assertRaisesRegex(PROVISION.ProvisionError, "root local target"):
            PROVISION.locked_packages({"packages": packages})


if __name__ == "__main__":
    unittest.main()
