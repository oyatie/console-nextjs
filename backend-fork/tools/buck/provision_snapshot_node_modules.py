#!/usr/bin/env python3
"""Link a verified lockfile-consistent Node dependency tree into a snapshot."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from pathlib import Path


class ProvisionError(ValueError):
    pass


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fail(message: str) -> None:
    raise ProvisionError("snapshot-node-deps: " + message)


def package_lock_path(value: object, *, allow_root: bool = False) -> str:
    """Accept only canonical relative POSIX paths from an npm package lock."""
    if not isinstance(value, str) or (not value and not allow_root):
        fail("invalid package-lock path")
    if value == "" and allow_root:
        return value
    if (
        "\\" in value
        or value.startswith("/")
        or re.match(r"^[A-Za-z]:", value)
        or any(part in ("", ".", "..") for part in value.split("/"))
    ):
        fail(f"invalid package-lock path: {value}")
    return value


def normalized_link_target(resolved: object) -> str:
    target = package_lock_path(resolved)
    if target == "node_modules" or target.startswith("node_modules/"):
        fail(f"linked package resolved path must name a root local target: {target}")
    return target


def link_targets(packages: dict) -> dict[str, str]:
    targets: dict[str, str] = {}
    for path, entry in packages.items():
        if not path.startswith("node_modules/") or not isinstance(entry, dict) or entry.get("link") is not True:
            continue
        target = normalized_link_target(entry.get("resolved"))
        target_entry = packages.get(target)
        if not isinstance(target_entry, dict) or not isinstance(target_entry.get("version"), str):
            fail(f"linked package target has no resolved package version: {path}")
        targets[path] = target
    return targets


def is_link_metadata(path: str, entry: dict, targets: dict[str, str]) -> bool:
    if entry.get("extraneous") is not True or "version" in entry:
        return False
    for link_path, target in targets.items():
        parent = link_path.rsplit("/node_modules/", 1)[0] if "/node_modules/" in link_path else ""
        metadata_path = f"{parent}/{target}" if parent else target
        if path == metadata_path:
            return True
    return False


def locked_packages(lock: dict) -> dict[str, dict]:
    packages = lock.get("packages")
    if not isinstance(packages, dict):
        fail("package-lock packages map is required")
    for path in packages:
        package_lock_path(path, allow_root=True)
    targets = link_targets(packages)
    result: dict[str, dict] = {}
    for path, entry in packages.items():
        if not path.startswith("node_modules/"):
            continue
        if not isinstance(entry, dict):
            fail(f"package-lock entry is invalid: {path}")
        if entry.get("link") is True:
            if path not in targets:
                fail(f"linked package has no resolved path: {path}")
        elif not isinstance(entry.get("version"), str):
            if is_link_metadata(path, entry, targets):
                continue
            fail(f"package-lock lacks a resolved package version for {path}")
        result[path] = entry
    return result


def matches_npm_platform(values: object, actual: str) -> bool:
    """Implement npm's positive/negative os/cpu selector semantics."""
    if values is None:
        return True
    if not isinstance(values, list) or not all(isinstance(value, str) for value in values):
        fail("package-lock os/cpu selectors must be string arrays")
    positive = {value for value in values if not value.startswith("!")}
    negative = {value[1:] for value in values if value.startswith("!")}
    return actual not in negative and (not positive or actual in positive)


def package_may_be_omitted(entry: dict, platform: str, arch: str) -> bool:
    return bool(entry.get("optional")) or not matches_npm_platform(entry.get("os"), platform) or not matches_npm_platform(entry.get("cpu"), arch)


def provision(caller: Path, snapshot: Path, *, platform: str = sys.platform, arch: str | None = None) -> Path:
    caller = caller.resolve()
    arch = arch or os.uname().machine
    for filename in ("package.json", "package-lock.json"):
        source, candidate = caller / filename, snapshot / filename
        if not source.is_file() or not candidate.is_file():
            fail(f"{filename} must exist in caller and immutable snapshot")
        if digest(source) != digest(candidate):
            fail(f"{filename} digest differs from immutable snapshot")
    try:
        lock = json.loads((caller / "package-lock.json").read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        fail(f"invalid package-lock.json: {error}")
    modules = caller / "node_modules"
    if not modules.is_dir():
        fail("lockfile-installed node_modules is absent; run npm ci in the caller before preflight")
    for relative, expected in locked_packages(lock).items():
        installed = caller / relative
        target = None
        if expected.get("link") is True:
            target = (caller / expected["resolved"]).resolve()
            try:
                target.relative_to(caller)
            except ValueError:
                fail(f"linked package target escapes caller: {relative}")
        if not installed.exists():
            if package_may_be_omitted(expected, platform, arch):
                continue
            fail(f"installed package is absent: {relative}")
        if expected.get("link") is True:
            if not installed.is_symlink() or installed.resolve() != target:
                fail(f"installed linked package differs from lockfile: {relative}")
            continue
        manifest = installed / "package.json"
        if not manifest.is_file():
            fail(f"installed package manifest is absent: {relative}")
        try:
            actual = json.loads(manifest.read_text(encoding="utf-8")).get("version")
        except json.JSONDecodeError as error:
            fail(f"invalid installed package manifest for {relative}: {error}")
        if actual != expected["version"]:
            fail(f"installed package version differs from lockfile: {relative} ({actual!r} != {expected['version']!r})")
    destination = snapshot / "node_modules"
    if destination.exists() or destination.is_symlink():
        fail("snapshot already has node_modules; archive must not contain mutable dependencies")
    # This is a reference, never a copy: generators may read exact lockfile
    # dependencies but cannot treat a parent directory as an ambient resolver.
    os.symlink(modules, destination, target_is_directory=True)
    return destination


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--caller", required=True, type=Path)
    parser.add_argument("--snapshot", required=True, type=Path)
    args = parser.parse_args()
    try:
        destination = provision(args.caller.resolve(), args.snapshot.resolve())
    except (OSError, ProvisionError) as error:
        print(error, file=sys.stderr)
        return 1
    print(f"snapshot-node-deps: linked verified dependencies at {destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
